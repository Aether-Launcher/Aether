#!/bin/zsh
# Injects the macOS 26 app icon into a built Wails app bundle:
#   1. compiles the Icon Composer document (darwin/aether.icon) with actool
#      into Contents/Resources/Assets.car (Liquid Glass icon),
#   2. adds CFBundleIconName=aether to the bundle's Info.plist. The key is
#      injected HERE, not kept in the wails plist templates, so it can never
#      reference a missing Assets.car (e.g. it stays out of `wails dev`
#      bundles until this script has actually run against them),
#   3. re-signs the bundle ad hoc (the modifications invalidate the signature
#      wails produced).
#
# macOS 26+ renders the icon from Assets.car; older macOS versions ignore it
# and fall back to CFBundleIconFile (iconfile.icns, generated by wails from
# build/appicon.png).
#
# Runs automatically as a wails postBuildHook (see wails.json) after
# `wails build` / `wails dev` for darwin targets. Can also be run standalone,
# e.g. to refresh the icon without a full rebuild:
#   ./build/darwin/compile-icon.sh [path/to/App.app | path/to/its/binary]
# (default: build/bin/Aether.app)
#
# Requires Xcode 26+ (actool).
set -euo pipefail
# Icon Composer requires Xcode 26. Older toolchains keep the Wails legacy icon.
if ! command -v xcodebuild >/dev/null 2>&1; then
  echo "warning: xcodebuild unavailable; keeping the Wails-generated legacy icon"
  exit 0
fi
XCODE_MAJOR="$(xcodebuild -version | awk '/^Xcode / {print int($2)}')"
if [[ -z "$XCODE_MAJOR" || "$XCODE_MAJOR" -lt 26 ]]; then
  echo "warning: Xcode 26+ required for Icon Composer; keeping the Wails-generated legacy icon"
  exit 0
fi

# Resolve the repo root from the script's own location (postBuildHooks run
# with build/bin as the working directory).
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR/../.."

ICON_NAME="aether"
ICON_FILE="build/darwin/${ICON_NAME}.icon"

# Accept a .app path or the path of the binary inside it (wails' ${bin}).
case "${1:-}" in
  *.app/Contents/MacOS/*) APP_BUNDLE="${1%%/Contents/MacOS/*}" ;;
  *.app)                  APP_BUNDLE="$1" ;;
  "")                     APP_BUNDLE="build/bin/Aether.app" ;;
  *)  echo "error: cannot derive app bundle from '$1'" >&2; exit 1 ;;
esac

[[ -d "$ICON_FILE" ]]  || { echo "error: $ICON_FILE not found" >&2; exit 1; }
[[ -d "$APP_BUNDLE" ]] || { echo "error: $APP_BUNDLE not found" >&2; exit 1; }

INFO_PLIST="$APP_BUNDLE/Contents/Info.plist"
RESOURCES_DIR="$APP_BUNDLE/Contents/Resources"

PARTIAL_PLIST="$(mktemp -t actool-partial).plist"
trap 'rm -f "$PARTIAL_PLIST"' EXIT

# actool requires --output-partial-info-plist when --app-icon is given; the
# partial plist is discarded (the icon key is applied manually below).
xcrun actool --compile "$RESOURCES_DIR" \
  --platform macosx \
  --minimum-deployment-target 26.0 \
  --app-icon "$ICON_NAME" \
  --output-partial-info-plist "$PARTIAL_PLIST" \
  --errors --warnings --notices --output-format human-readable-text \
  "$ICON_FILE"

# Point CFBundleIconName at the compiled icon (insert-or-replace: rerunnable).
plutil -insert CFBundleIconName -string "$ICON_NAME" "$INFO_PLIST" 2>/dev/null \
  || plutil -replace CFBundleIconName -string "$ICON_NAME" "$INFO_PLIST"

# The modifications invalidate the bundle signature wails produced; re-sign ad hoc.
codesign --force --sign - "$APP_BUNDLE"

echo "OK: $APP_BUNDLE <- Assets.car + CFBundleIconName=$ICON_NAME"
